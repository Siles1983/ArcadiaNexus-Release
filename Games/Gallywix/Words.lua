function W:GetEntries(category, locale)
    local valid = false
    for _, value in ipairs(self.categories) do if value == category then valid = true end end
    if not valid then return {} end
    local column = (locale or A.ActiveLocale or "enUS") == "deDE" and 3 or 4
    local result = {}
    for _, entry in ipairs(entries) do
        if category == "all" or category == entry[2] then
            result[#result + 1] = { id = entry[1], category = entry[2], answer = entry[column] }
        end
    end
    return result
end
-- Data-selection memory lasts until /reload. Categories share their seen IDs
-- within a language, so switching to "all" also favors unselected phrases.
local selectionMemory = {}
function W:NewDeck(category, locale)
    local language=locale or A.ActiveLocale or "enUS"
    local pool=A.ArrayUtils.Shuffle(self:GetEntries(category or "all",language))
    if #pool<3 then return {} end
    local memory=selectionMemory[language]
    if not memory then memory={seen={},recent={}}; selectionMemory[language]=memory end
    local unseen,unseenIds={},{}
    for _,entry in ipairs(pool) do
        if not memory.seen[entry.id] then unseen[#unseen+1]=entry; unseenIds[entry.id]=true end
    end
    if #unseen<3 then
        -- Finish the old cycle first; then begin a newly shuffled cycle.
        -- Defer the previous game's IDs so the boundary does not repeat it.
        for _,entry in ipairs(pool) do memory.seen[entry.id]=nil end
        for _,entry in ipairs(pool) do
            if not unseenIds[entry.id] and not memory.recent[entry.id] then unseen[#unseen+1]=entry end
        end
        for _,entry in ipairs(pool) do
            if not unseenIds[entry.id] and memory.recent[entry.id] then unseen[#unseen+1]=entry end
        end
    end
    local deck={}
    memory.recent={}
    for i=1,3 do
        local entry=unseen[i]
        deck[i]=entry
        memory.seen[entry.id]=true
        memory.recent[entry.id]=true
    end
    return deck
end
